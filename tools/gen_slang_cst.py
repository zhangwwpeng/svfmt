#!/usr/bin/env python3
"""Generate the typed slang -> Verible CST conversion from slang's syntax.txt.

slang flattens list members into their parent when iterating children, but
Verible's formatter expects list nodes (module item list, port list, ...).
This script emits, for every slang syntax class, code that converts its
members in order and wraps each list member into a synthetic list node tagged
with a ListKind value (named <Class>_<member>).

usage: gen_slang_cst.py <slang/scripts dir> <output dir>
writes: list-kinds.h, slang-cst-gen.inc
"""
import os
import sys

scripts_dir, out_dir = sys.argv[1], sys.argv[2]
sys.path.insert(0, scripts_dir)
from syntax_gen import loadalltypes  # noqa: E402

alltypes, kindmap = loadalltypes(scripts_dir)

by_class = {}
for kind, cls in sorted(kindmap.items()):
    by_class.setdefault(cls, []).append(kind)

LIST_BASE = 10000
list_kinds = []  # (enum name, class, member)
cases = []
for cls in sorted(by_class):
    info = alltypes[cls]
    short = cls[: -len("Syntax")]
    body = []
    for pm in info.processedMembers:
        mtype, name = pm.rsplit(" ", 1)
        if mtype == "Token":
            body.append(f"b.Tok(n.{name}, out);")
        elif mtype == "TokenList":
            body.append(f"b.Toks(n.{name}, out);")
        elif mtype.startswith(("SyntaxList<", "SeparatedSyntaxList<")):
            enum = f"{short}_{name}"
            list_kinds.append(enum)
            body.append(f"b.List(n.{name}, static_cast<int>(ListKind::{enum}), out);")
        elif mtype.endswith("&"):
            body.append(f"b.Child(n.{name}.get(), out);")
        elif mtype.endswith("*"):
            body.append(f"b.Child(n.{name}, out);")
        else:
            raise ValueError(f"unhandled member {pm} in {cls}")
    labels = " ".join(f"case SyntaxKind::{k}:" for k in by_class[cls])
    cases.append(f"{labels} {{\n  const auto &n = node.as<{cls}>();\n  (void)n;\n  "
                 + "\n  ".join(body) + "\n  return;\n}")

with open(os.path.join(out_dir, "list-kinds.h"), "w") as f:
    f.write("// DO NOT EDIT -- generated by tools/gen_slang_cst.py from slang's syntax.txt\n")
    f.write("#ifndef SVFMT_LIST_KINDS_H_\n#define SVFMT_LIST_KINDS_H_\n\n#include <string_view>\n\n")
    f.write("namespace svfmt {\n\n")
    f.write("// Tags of synthetic list nodes: <slang syntax class>_<member>.\n")
    f.write("enum class ListKind : int {\n")
    for i, e in enumerate(list_kinds):
        f.write(f"  {e} = {LIST_BASE + i},\n")
    f.write("};\n\n")
    f.write(f"inline constexpr int kFirstListKind = {LIST_BASE};\n")
    f.write(f"inline constexpr int kLastListKind = {LIST_BASE + len(list_kinds) - 1};\n\n")
    f.write("inline bool IsListTag(int tag) { return tag >= kFirstListKind && tag <= kLastListKind; }\n\n")
    f.write("inline std::string_view ListKindName(int tag) {\n  static constexpr std::string_view kNames[] = {\n")
    for e in list_kinds:
        f.write(f'      "{e}",\n')
    f.write("  };\n  return IsListTag(tag) ? kNames[tag - kFirstListKind] : std::string_view();\n}\n\n")
    f.write("}  // namespace svfmt\n\n#endif  // SVFMT_LIST_KINDS_H_\n")

with open(os.path.join(out_dir, "slang-cst-gen.inc"), "w") as f:
    f.write("// DO NOT EDIT -- generated by tools/gen_slang_cst.py from slang's syntax.txt\n")
    f.write("// Body of: template <class B> void ConvertMembers(B &b, const SyntaxNode &node,\n")
    f.write("//                                               SyntaxTreeNode &out)\n")
    f.write("switch (node.kind) {\n")
    for c in cases:
        f.write(c + "\n")
    f.write("default:\n  break;\n}\n")
print(f"{len(by_class)} classes, {len(list_kinds)} list kinds")
