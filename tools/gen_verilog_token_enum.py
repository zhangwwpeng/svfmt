#!/usr/bin/env python3
"""Generate src/verible/verilog/parser/verilog-token-enum.h from Verible's verilog.y.

Verible gets this header from bison's verilog.tab.hh. We have no parser, so we
reproduce bison's numbering: explicit values are kept, single-character tokens
use their ASCII value, and named tokens are numbered from 258 in declaration
order. Alias strings ("<=", "module", ...) are emitted too, so the slang token
bridge can map slang tokens by their text.

usage: gen_verilog_token_enum.py path/to/verilog.y > verilog-token-enum.h
"""
import re
import sys

src = open(sys.argv[1]).read()
tokens = []  # (name, value or None, alias or None)
decl = re.compile(r'^%(token|left|right|nonassoc|precedence)\b(.*)$', re.M)
for m in decl.finditer(src.split('\n%%', 1)[0]):
    if m.group(1) == 'token':
        t = re.match(r'\s+(?:<\w+>\s+)?(\w+)(?:\s+(\d+))?(?:\s+("(?:[^"\\]|\\.)*"))?', m.group(2))
        if t:
            tokens.append((t.group(1), t.group(2), t.group(3)))
    else:
        # Precedence declarations can introduce new token names.
        body = re.sub(r"'(?:[^'\\]|\\.)*'|//.*", ' ', m.group(2))
        for name in re.findall(r'\b[A-Za-z_]\w*\b', body):
            tokens.append((name, None, None))

seen = set()
out = []
next_value = 258
for name, value, alias in tokens:
    if name in seen:
        continue
    seen.add(name)
    if value is None:
        value = next_value
        next_value += 1
    out.append((name, int(value), alias))

print("// DO NOT EDIT -- generated by tools/gen_verilog_token_enum.py from verilog.y")
print("#ifndef VERIBLE_VERILOG_TOKEN_ENUM_H_")
print("#define VERIBLE_VERILOG_TOKEN_ENUM_H_")
print()
print("#ifndef VERILOG_TOKENTYPE")
print("#define VERILOG_TOKENTYPE")
print("enum verilog_tokentype {")
for name, value, _ in out:
    print(f"  {name} = {value},")
print("};")
print("#endif")
print()
print("namespace verilog {")
print("struct VerilogTokenInfoEntry { int value; const char *name; const char *alias; };")
print("inline constexpr VerilogTokenInfoEntry kVerilogTokenTable[] = {")
for name, value, alias in out:
    print(f'  {{{value}, "{name}", {alias if alias else "nullptr"}}},')
print("};")
print("}  // namespace verilog")
print()
print("#endif  // VERIBLE_VERILOG_TOKEN_ENUM_H_")
